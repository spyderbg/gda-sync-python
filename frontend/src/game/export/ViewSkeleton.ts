// The C++ of a view made in the browser that the C++ game does not have yet: a skeleton that compiles, so that the
// exported plugin builds, and that loads the view's elements list. Its behavior (what its TypeScript does with the
// elements, the interface it provides) is ported by hand: the skeleton names the TypeScript file and its interfaces.

export interface ViewSkeletonInput {
  /** The view module, such as BurningCrownTetraSpins10View. */
  viewModule: string;
  /** Views or SwButtons. */
  folder: string;
  className: string;
  /** The TypeScript file, relative to frontend/src/game, and its source. */
  tsPath: string;
  tsSource: string;
}

/** The view's ids, the `const XxxId = '...'` of its TypeScript, and the interfaces it implements. */
function Facts(source: string, className: string) {
  const ids = [...source.matchAll(/^const (\w+Id) = '([^']*)';$/gm)].map(([, name, value]) => ({ name, value }));
  const implemented = source.match(new RegExp(`class ${className} extends \\w+(?:<[^>]*>)? implements ([\\w, ]+)`))?.[1]
    .split(',').map(name => name.trim()).filter(Boolean) ?? [];
  const viewId = ids.find(id => id.name === `${className}Id`) ?? { name: `${className}Id`, value: className };
  return { ids: ids.some(id => id.name === viewId.name) ? ids : [viewId, ...ids], viewId, implemented };
}

export function ViewSkeleton(input: ViewSkeletonInput): Record<string, string> {
  const { className, viewModule, folder } = input;
  const facts = Facts(input.tsSource, className);
  const todo = facts.implemented.length ? `\n    // TODO: implement ${facts.implemented.join(', ')}, as ${input.tsPath} does.` : '';
  const header = `#pragma once

// Generated by the browser game: a skeleton of ${className} (frontend/src/game/${input.tsPath}), a view the C++ game does
// not have yet. It loads its elements list; port the rest from the TypeScript.

#include <Egt/AlphaFamilyVideoCtrl/BaseView.h>

namespace Egt::Game::AlphaFamily
{
    class ${className} : public BaseView
    {${todo}
    public:
        ${className}();
        ~${className}() override;

        bool Init(GameCore::RuntimeAccess) override;
        void Deinit() override;

    private:
        void OnElementsListLoaded();
    };
}
`;
  const cpp = `#include "${className}.h"

#include <Egt/GameCore/Common/Defensive.h>

#include <string_view>

namespace Egt::Game::AlphaFamily
{
    namespace
    {
${facts.ids.map(id => `        [[maybe_unused]] constexpr std::string_view ${id.name} = "${id.value}";`).join('\n')}
    }

    ${className}::${className}()
        : BaseView(std::string(${facts.viewId.name}))
    {
    }

    ${className}::~${className}() = default;

    bool ${className}::Init(GameCore::RuntimeAccess runtime)
    {
        AssertReturnUnless(BaseView::Init(std::move(runtime)), false);

        InitElementsList(${facts.viewId.name}, [this] {
            this->OnElementsListLoaded();
        });

        return true;
    }

    void ${className}::Deinit()
    {
        DeinitElementsList();
        BaseView::Deinit();
    }

    void ${className}::OnElementsListLoaded()
    {
        // TODO: port from frontend/src/game/${input.tsPath}
    }
}
`;
  const base = `${viewModule}/${folder}/${className}`;
  return { [`${base}.h`]: header, [`${base}.cpp`]: cpp };
}
